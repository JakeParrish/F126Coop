// Converts the bacinger/f1-circuits GeoJSON (OpenStreetMap-derived, MIT) into a
// compact SVG-path lookup for just the circuits on our 2026 calendar.
// Run: node scripts/gen-circuits.mjs
import { readFileSync, writeFileSync } from "node:fs";

// round -> circuit id in the dataset (kept in sync with server CALENDAR)
const ROUND_TO_CIRCUIT = {
  1: "au-1953",
  2: "cn-2004",
  3: "jp-1962",
  4: "bh-2002",
  5: "sa-2021",
  6: "us-2022",
  7: "ca-1978",
  8: "mc-1929",
  9: "es-1991",
  10: "at-1969",
  11: "gb-1948",
  12: "be-1925",
  13: "hu-1986",
  14: "nl-1948",
  15: "it-1922",
  16: "es-2026",
  17: "az-2016",
  18: "sg-2008",
  19: "us-2012",
  20: "mx-1962",
  21: "br-1940",
  22: "us-2023",
  23: "qa-2004",
  24: "ae-2009",
};

const SIZE = 1000; // target viewBox extent for the longer axis
const PAD = 40;

const geo = JSON.parse(readFileSync("./_f1c.geojson", "utf8"));
const byId = new Map(geo.features.map((f) => [f.properties.id, f]));

function longestLine(geom) {
  if (geom.type === "LineString") return geom.coordinates;
  if (geom.type === "MultiLineString") {
    return geom.coordinates.reduce((a, b) => (b.length > a.length ? b : a), []);
  }
  if (geom.type === "Polygon") return geom.coordinates[0];
  return [];
}

function toPath(coords) {
  // Equirectangular projection with longitude compressed by cos(latitude).
  const meanLat = coords.reduce((s, c) => s + c[1], 0) / coords.length;
  const k = Math.cos((meanLat * Math.PI) / 180);
  const pts = coords.map(([lon, lat]) => ({ x: lon * k, y: lat }));

  const xs = pts.map((p) => p.x);
  const ys = pts.map((p) => p.y);
  const minX = Math.min(...xs), maxX = Math.max(...xs);
  const minY = Math.min(...ys), maxY = Math.max(...ys);
  const w = maxX - minX || 1;
  const h = maxY - minY || 1;
  const scale = (SIZE - PAD * 2) / Math.max(w, h);
  const offX = (SIZE - w * scale) / 2;
  const offY = (SIZE - h * scale) / 2;

  const proj = pts.map((p) => {
    const x = offX + (p.x - minX) * scale;
    // Flip Y so north is up in SVG coordinates.
    const y = offY + (maxY - p.y) * scale;
    return [Math.round(x * 10) / 10, Math.round(y * 10) / 10];
  });

  const vbW = Math.round(w * scale + offX * 2);
  const vbH = Math.round(h * scale + offY * 2);
  const d =
    "M" +
    proj.map(([x, y]) => `${x} ${y}`).join(" L ") +
    " Z";
  return { d, viewBox: `0 0 ${vbW} ${vbH}` };
}

const out = {};
for (const [round, id] of Object.entries(ROUND_TO_CIRCUIT)) {
  const f = byId.get(id);
  if (!f) {
    console.warn(`!! missing circuit ${id} (round ${round})`);
    continue;
  }
  const coords = longestLine(f.geometry);
  const { d, viewBox } = toPath(coords);
  out[id] = {
    id,
    name: f.properties.Name,
    location: f.properties.Location ?? "",
    length: f.properties.length ?? null,
    viewBox,
    d,
  };
}

const ts = `// AUTO-GENERATED by scripts/gen-circuits.mjs — do not edit by hand.
// Circuit outlines derived from bacinger/f1-circuits (MIT), built from
// OpenStreetMap data © OpenStreetMap contributors (ODbL).

export interface Circuit {
  id: string;
  name: string;
  location: string;
  length: number | null;
  viewBox: string;
  d: string;
}

export const ROUND_TO_CIRCUIT: Record<number, string> = ${JSON.stringify(
  Object.fromEntries(Object.entries(ROUND_TO_CIRCUIT).map(([k, v]) => [Number(k), v])),
  null,
  2
)};

export const CIRCUITS: Record<string, Circuit> = ${JSON.stringify(out, null, 2)};

export function circuitForRound(round: number): Circuit | null {
  const id = ROUND_TO_CIRCUIT[round];
  return id ? CIRCUITS[id] ?? null : null;
}
`;

writeFileSync("./client/src/data/circuits.ts", ts);
const bytes = Buffer.byteLength(ts);
console.log(`Wrote client/src/data/circuits.ts (${out && Object.keys(out).length} circuits, ${bytes} bytes)`);
